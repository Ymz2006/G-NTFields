#!/usr/bin/env python3
"""Host-side queue for the expanded comparison of the 8000-epoch homotopy head against the original metric NTFields
(2026-10-17, second request), one GPU, GPU-memory-aware. Two tracks:

  targeted   the metric baseline (bundle /home/jeffrey/export_metric, 8000 epochs, epoch-4000 checkpoint kept) is
             trained on the three standard cells; it and the 8000-epoch homotopy runs are scored on the targeted sets
             (testing_data/3dshape/<scene>_{long,bigrot,tight,hard}, generated by make_test_sets.py) and the standard
             sets with plan_eval_homotopy.py.
  wall       the wall-with-hole cells (datasets/3dshape/<shape>_hole{90,75,66}, make_wall_envs.py): preprocessing
             (Lie repo preprocess_obj.py, 800k pairs), through-the-hole test sets (make_test_sets.py --variant through),
             both models trained per cell (seed 0 first, then seed 1) and scored on the through sets.

    python3 models/graph_homotopy/scripts/run_expand_queue.py            # run everything (resumable)
    python3 models/graph_homotopy/scripts/run_expand_queue.py --dry-run  # list jobs and their state

Jobs are launched in priority order when their dependencies are done and the GPU memory estimate fits
(--gpu-budget GB, estimates per job kind) and the actual free memory confirms it. Containers: gxp_ preprocess,
gxs_ set generation (CPU), gxt_ training, gxe_ evaluation; running ones are adopted on restart. Status:
results/graph_homotopy/queue_status_expand.json. Standard library only.
"""
import argparse
import json
import os
import subprocess
import sys
import time

HOST = '/home/jeffrey/G-NTFields'
LIE = '/home/jeffrey/Lie-Shape-NTFields'
EXPORT = '/home/jeffrey/export_metric'
IMAGE = 'ntfields:rtx5070'
EXP_H = 'Experiments/graph_homotopy'
EXP_M = 'Experiments/metric_baseline'
RES = 'results/graph_homotopy/plan_expand'
SETS = 'testing_data/3dshape'                                   # new sets, in HOST
DATA = 'datasets/3dshape'
SCENES = {'T': 'Tshape3d_env1', 'L': 'Lshape3d_env3', 'A': 'Ashape3d_env4'}
SHAPES = {'T': 'Tshape3d', 'L': 'Lshape3d', 'A': 'Ashape3d'}
VARIANTS = ('long', 'bigrot', 'tight', 'hard')
HOLES = ('90', '75', '66')
OUR_SEEDS = (0, 1, 2, 3, 4)
MB_SEEDS = (0, 1, 2)
WALL_SEEDS = (0, 1)
PRE_ORDER = ['Tshape3d_hole90', 'Tshape3d_hole75', 'Tshape3d_hole66', 'Lshape3d_hole66', 'Ashape3d_hole66',
             'Lshape3d_hole90', 'Ashape3d_hole90', 'Lshape3d_hole75', 'Ashape3d_hole75']
PRE_SAMPLES = 200000
PRE_BATCH = 100          # evaluate_placements chunk (about 3.1 GB)
EPOCHS = 8000
MEM = {'pre': 3.3, 'mb': 3.0, 'hom': 0.65, 'eval': 0.6, 'set': 0.0}   # GB estimates per job kind


def sh(cmd):
    return subprocess.run(cmd, shell=True, capture_output=True, text=True).stdout


def containers():
    return [n for n in sh("docker ps --format '{{.Names}}'").split() if n.startswith(('gxt_', 'gxe_', 'gxp_', 'gxs_'))]


def gpu_free_gb():
    try:
        used, total = sh("nvidia-smi --query-gpu=memory.used,memory.total --format=csv,noheader,nounits").strip().split(',')
        return (float(total) - float(used)) / 1024.0
    except Exception:
        return 0.0


def complete_json(path):
    try:
        with open(path, 'rb') as fh:
            fh.seek(max(0, os.path.getsize(path) - 64))
            return fh.read().rstrip().endswith(b'}')
    except OSError:
        return False


def exists(*parts):
    return os.path.exists(os.path.join(HOST, *parts))


def docker_prefix(cname, workdir, gpu=True, threads=2, extra_env=''):
    return ('docker run -d --rm {gpu} -u {uid}:{gid} -e HOME=/tmp -e MPLCONFIGDIR=/tmp -e PYTHONDONTWRITEBYTECODE=1 '
            '-e OMP_NUM_THREADS={th} {ee} -v {host}:/workspace -v {lie}:/lieshape:ro -v {exp}:/export:ro -w {wd} '
            '--name {c} {img} ').format(gpu='--gpus all' if gpu else '', uid=os.getuid(), gid=os.getgid(), th=threads,
                                        ee=extra_env, host=HOST, lie=LIE, exp=EXPORT, wd=workdir, c=cname, img=IMAGE)


# ----------------------------------------------------------------------------- job table
class Job:
    def __init__(self, name, kind, prio, done, launch, deps=(), cname=None):
        self.name, self.kind, self.prio, self.done, self.launch, self.deps = name, kind, prio, done, launch, deps
        self.cname = cname or name

    def ready(self, done_of):
        return all(done_of(d) for d in self.deps)


def cell_done(cell):
    return all(exists(DATA, cell, f) for f in ('sampled_points.npy', 'speed.npy', 'normal.npy', 'meta.json'))


def set_done(setname):
    return exists(SETS, setname, 'verification.json') and exists(SETS, setname, 'sampled_points.npy')


def train_done_mb(name):
    return exists(EXP_M, name, 'train_summary.json') and exists(EXP_M, name, 'latest.pt')


def train_done_h(name):
    return exists(EXP_H, name, 'train_summary.json') and exists(EXP_H, name, 'latest.pt')


def eval_done(run, setname, planner):
    return complete_json(os.path.join(HOST, RES, run, '{}__{}.json'.format(setname, planner)))


def launch_pre(cell, shape, env):
    os.makedirs(os.path.join(HOST, DATA, 'logs'), exist_ok=True)
    args = ('python -u /workspace/models/graph_homotopy/scripts/preprocess_hole.py --env /workspace/{d}/{env}.obj '
            '--shape /workspace/{d}/{shape}.obj --out /workspace/{d}/{cell} --num_samples {ns} --device cuda '
            '--eval_chunk {bs}').format(d=DATA, env=env, shape=shape, cell=cell, ns=PRE_SAMPLES, bs=PRE_BATCH)
    sh(docker_prefix('gxp_' + cell, '/lieshape', extra_env='-e PYTORCH_CUDA_ALLOC_CONF=expandable_segments:True')
       + '/bin/bash -c "{} > /workspace/{}/logs/pre_{}.out 2>&1"'.format(args, DATA, cell))


def launch_set(scene, variant, workers):
    os.makedirs(os.path.join(HOST, SETS, 'logs'), exist_ok=True)
    args = ('python -u /workspace/models/graph_homotopy/scripts/make_test_sets.py --scene {sc} --variant {v} --n 1000 '
            '--workers {w} --out /workspace/{sets}').format(sc=scene, v=variant, w=workers, sets=SETS)
    sh(docker_prefix('gxs_{}_{}'.format(scene, variant), '/lieshape', gpu=False, threads=1)
       + '/bin/bash -c "{} > /workspace/{}/logs/{}_{}.out 2>&1"'.format(args, SETS, scene, variant))


def launch_train_mb(name, cell, seed):
    os.makedirs(os.path.join(HOST, EXP_M, 'logs'), exist_ok=True)
    args = ('python -u /workspace/train/train_metric_baseline.py --dataPath /workspace/{d}/{cell} --name {n} --seed {s} '
            '--epochs {ep} --bundle /export --out_root /workspace/{exp}').format(d=DATA, cell=cell, n=name, s=seed, ep=EPOCHS, exp=EXP_M)
    sh(docker_prefix('gxt_' + name, '/export') + '/bin/bash -c "{} > /workspace/{}/logs/{}.out 2>&1"'.format(args, EXP_M, name))


def launch_train_h(name, cell, seed):
    os.makedirs(os.path.join(HOST, EXP_H, 'logs'), exist_ok=True)
    args = ('python -u train/train_graph_homotopy.py --dataPath {d}/{cell} --name {n} --seed {s} --epochs {ep} '
            '--lift min --lift-far 0.5').format(d=DATA, cell=cell, n=name, s=seed, ep=EPOCHS)
    sh(docker_prefix('gxt_' + name, '/workspace') + '/bin/bash -c "{} > {}/logs/{}.out 2>&1"'.format(args, EXP_H, name))


def launch_eval(run, kind, ckpt, setname, setpath, planner, workers):
    out = '/workspace/{}/{}'.format(RES, run)
    os.makedirs(os.path.join(HOST, RES, run), exist_ok=True)
    args = ('python -u /workspace/models/graph_homotopy/scripts/plan_eval_homotopy.py --planner {p} --kind {k} '
            '--checkpoint {ck} --dataPath {sp} --out {o}/{s}__{p}.json --device cuda:0 --batch 125 --workers {w} '
            '--seed 0 --metric-root /export').format(p=planner, k=kind, ck=ckpt, sp=setpath, o=out, s=setname, w=workers)
    sh(docker_prefix('gxe_{}__{}__{}'.format(run, setname, planner), '/lieshape', threads=1)
       + '/bin/bash -c "{} > {}/{}__{}.log 2>&1"'.format(args, out, setname, planner))


def build_jobs(a):
    J = []
    planners = a.planners.split(',')

    def add(*args, **kw):
        J.append(Job(*args, **kw))

    def add_evals(run, kind, ckpt_host, ckpt_cont, sets, prio, plans, deps):
        if not os.path.exists(ckpt_host) and not deps:
            return
        for sname, spath in sets:
            for pi, p in enumerate(plans):
                add('eval:{}:{}:{}'.format(run, sname, p), 'eval', prio + 0.01 * pi,
                    (lambda r=run, s=sname, pp=p: eval_done(r, s, pp)),
                    (lambda r=run, k=kind, c=ckpt_cont, s=sname, sp=spath, pp=p: launch_eval(r, k, c, s, sp, pp, a.eval_workers)),
                    deps=deps, cname='gxe_{}__{}__{}'.format(run, sname, p))

    # --- wall track: preprocessing and through sets
    for hole in HOLES:
        for sc, shape in SHAPES.items():
            cell = '{}_hole{}'.format(shape, hole)
            add('pre:' + cell, 'pre', 0 + 0.01 * PRE_ORDER.index(cell), (lambda c=cell: cell_done(c)), (lambda c=cell, s=shape, h=hole: launch_pre(c, s, 'hole' + h)),
                cname='gxp_' + cell)
            add('set:{}_through'.format(cell), 'set', 2 + 0.01 * PRE_ORDER.index(cell), (lambda c=cell: set_done(c + '_through')),
                (lambda c=cell: launch_set(c, 'through', a.set_workers)), deps=('pre:' + cell,), cname='gxs_{}_through'.format(cell))
    # --- targeted track: baseline trainings on the standard cells
    for sc, scene in SCENES.items():
        for s in MB_SEEDS:
            n = '{}_mb_s{}'.format(sc, s)
            add('train:' + n, 'mb', 1, (lambda nn=n: train_done_mb(nn)), (lambda nn=n, c=scene, ss=s: launch_train_mb(nn, c, ss)), cname='gxt_' + n)
    # --- wall track: trainings
    for si, seed in enumerate(WALL_SEEDS):
        for hole in HOLES:
            for sc, shape in SHAPES.items():
                if si > 0 and sc != 'T':
                    continue
                cell = '{}_hole{}'.format(shape, hole)
                code = '{}{}'.format(sc, hole)
                nh = '{}_hminL_s{}'.format(code, seed)
                nm = '{}_mb_s{}'.format(code, seed)
                prio = (3 if si == 0 else 6) + 0.01 * PRE_ORDER.index(cell)
                add('train:' + nh, 'hom', prio, (lambda nn=nh: train_done_h(nn)), (lambda nn=nh, c=cell, ss=seed: launch_train_h(nn, c, ss)),
                    deps=('pre:' + cell,), cname='gxt_' + nh)
                # the baseline trainer needs 3 GB: queue it behind the evaluations (0.5 GB, CPU-bound) so that at most
                # one or two run at a time and the evaluations are not starved of GPU memory
                add('train:' + nm, 'mb', prio + 1.5, (lambda nn=nm: train_done_mb(nn)), (lambda nn=nm, c=cell, ss=seed: launch_train_mb(nn, c, ss)),
                    deps=('pre:' + cell,), cname='gxt_' + nm)
    # --- targeted track: evaluations
    for sc, scene in SCENES.items():
        new_sets = [('{}_{}'.format(scene, v), '/workspace/{}/{}_{}'.format(SETS, scene, v)) for v in VARIANTS
                    if set_done('{}_{}'.format(scene, v))]
        std = [(scene, 'testing_data/3dshape/' + scene)]
        for s in OUR_SEEDS:
            run = '{}_hminL_s{}'.format(sc, s)
            add_evals(run, 'graph', os.path.join(HOST, EXP_H, run, 'latest.pt'), '/workspace/{}/{}/latest.pt'.format(EXP_H, run),
                      new_sets, 4, planners, deps=())
        for s in MB_SEEDS:
            n = '{}_mb_s{}'.format(sc, s)
            d = '/workspace/{}/{}'.format(EXP_M, n)
            add_evals(n, 'metric', '', d + '/latest.pt', new_sets + std, 4, ['base'], deps=('train:' + n,))
            add_evals('{}_mb4k_s{}'.format(sc, s), 'metric', '', d + '/epoch4000.pt', std, 7, ['base'], deps=('train:' + n,))
            add_evals('{}_mb4k_s{}'.format(sc, s), 'metric', '', d + '/epoch4000.pt', new_sets, 7.5, ['base'], deps=('train:' + n,))
    # --- wall track: evaluations
    for si, seed in enumerate(WALL_SEEDS):
        for hole in HOLES:
            for sc, shape in SHAPES.items():
                if si > 0 and sc != 'T':
                    continue
                cell = '{}_hole{}'.format(shape, hole)
                code = '{}{}'.format(sc, hole)
                sets = [(cell + '_through', '/workspace/{}/{}_through'.format(SETS, cell))]
                nh = '{}_hminL_s{}'.format(code, seed)
                nm = '{}_mb_s{}'.format(code, seed)
                prio = 4.005 if si == 0 else 7.2      # seed-0 wall evaluations as soon as their cell is ready
                add_evals(nh, 'graph', '', '/workspace/{}/{}/latest.pt'.format(EXP_H, nh), sets, prio, planners,
                          deps=('train:' + nh, 'set:{}_through'.format(cell)))
                add_evals(nm, 'metric', '', '/workspace/{}/{}/latest.pt'.format(EXP_M, nm), sets, prio, ['base'],
                          deps=('train:' + nm, 'set:{}_through'.format(cell)))
                add_evals('{}_mb4k_s{}'.format(code, seed), 'metric', '', '/workspace/{}/{}/epoch4000.pt'.format(EXP_M, nm), sets, 7.1 + si,
                          ['base'], deps=('train:' + nm, 'set:{}_through'.format(cell)))
    return sorted(J, key=lambda j: (j.prio, j.name))


def main():
    ap = argparse.ArgumentParser()
    ap.add_argument('--gpu-budget', type=float, default=11.6)
    ap.add_argument('--max-gpu-jobs', type=int, default=7)
    ap.add_argument('--max-train', type=int, default=5)
    ap.add_argument('--max-eval', type=int, default=3)
    ap.add_argument('--max-set', type=int, default=2)
    ap.add_argument('--max-pre', type=int, default=1)
    ap.add_argument('--eval-workers', type=int, default=4)
    ap.add_argument('--set-workers', type=int, default=10)
    ap.add_argument('--planners', default='base,dual')
    ap.add_argument('--poll', type=float, default=30.0)
    ap.add_argument('--attempts', type=int, default=2)
    ap.add_argument('--dry-run', action='store_true')
    a = ap.parse_args()
    if a.dry_run:
        for j in build_jobs(a):
            print('{:5.2f} {:5s} {:60s} {}'.format(j.prio, j.kind, j.name, 'done' if j.done() else ''))
        return
    attempts, failed, launched = {}, {}, {}
    t0 = time.time()
    while True:
        jobs = build_jobs(a)
        by_name = {j.name: j for j in jobs}
        live = set(containers())
        # bookkeeping of launched jobs that are no longer running
        for n, cname in list(launched.items()):
            if cname not in live:
                j = by_name.get(n)
                if j is not None and not j.done():
                    attempts[n] = attempts.get(n, 0) + 1
                    if attempts[n] >= a.attempts:
                        failed[n] = 'exited without result after {} attempts'.format(attempts[n])
                del launched[n]
        # memory accounting of everything running (adopted containers included)
        kind_of = {'gxp_': 'pre', 'gxs_': 'set', 'gxt_': 'train', 'gxe_': 'eval'}
        used = 0.0
        n_train = n_eval = n_set = n_gpu = n_pre = 0
        for c in live:
            k = kind_of[c[:4]]
            if k == 'train':
                used += MEM['mb'] if '_mb_' in c else MEM['hom']
                n_train += 1
            else:
                used += MEM[k]
            n_eval += k == 'eval'
            n_set += k == 'set'
            n_pre += k == 'pre'
            n_gpu += k != 'set'
        done_of = lambda n: by_name[n].done() if n in by_name else False  # noqa: E731
        pend = [j for j in jobs if not j.done() and j.cname not in live and j.name not in failed and j.ready(done_of)]
        free_actual = gpu_free_gb()
        for j in pend:
            if j.kind == 'set':
                if n_set >= a.max_set:
                    continue
            else:
                need = MEM['mb'] if (j.kind == 'mb') else MEM[j.kind]
                if n_gpu >= a.max_gpu_jobs or used + need > a.gpu_budget or free_actual < need + 0.4:
                    continue
                if j.kind in ('mb', 'hom') and n_train >= a.max_train:
                    continue
                if j.kind == 'eval' and n_eval >= a.max_eval:
                    continue
                if j.kind == 'pre' and n_pre >= a.max_pre:
                    continue
            j.launch()
            launched[j.name] = j.cname
            print('[{:6.0f}s] launch {}'.format(time.time() - t0, j.name), flush=True)
            if j.kind == 'set':
                n_set += 1
            else:
                used += need
                free_actual -= need
                n_gpu += 1
                n_train += j.kind in ('mb', 'hom')
                n_eval += j.kind == 'eval'
                n_pre += j.kind == 'pre'
            time.sleep(3)
        status = {'time': time.strftime('%Y-%m-%d %H:%M:%S'), 'elapsed_s': time.time() - t0,
                  'done': sum(j.done() for j in jobs), 'total': len(jobs),
                  'by_kind': {k: [sum(j.done() for j in jobs if j.kind == k), sum(1 for j in jobs if j.kind == k)]
                              for k in ('pre', 'set', 'mb', 'hom', 'eval')},
                  'running': sorted(live), 'mem_est_gb': used, 'gpu_free_gb': gpu_free_gb(), 'failed': failed}
        try:
            dst = os.path.join(HOST, 'results/graph_homotopy/queue_status_expand.json')
            with open(dst + '.tmp', 'w') as fh:
                json.dump(status, fh, indent=1)
            os.replace(dst + '.tmp', dst)
        except OSError as e:
            print('status not written: {}'.format(e), flush=True)
        if all(j.done() or j.name in failed for j in jobs) and not live:
            print('all done; failed: {}'.format(failed), flush=True)
            return
        time.sleep(a.poll)


if __name__ == '__main__':
    sys.exit(main())
