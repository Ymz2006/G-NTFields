#!/usr/bin/env python3
"""Tables for the synthetic exact-truth benchmark: supervised fits (results/graph_branch/synth/<problem>/<head>_s<seed>.json)
and physics-trained fields (results/graph_branch/synth_phys/<run>.json). mean +- sd over seeds.

    python3 models/graph_branch/scripts/aggregate_synth.py   # -> results/graph_branch/summary/synth_summary.{md,json}
"""
import glob
import json
import os
import re
import statistics as st

HOST = '/media/jeffrey/G-Shape-NTFields'
SUP = os.path.join(HOST, 'results/graph_branch/synth')
PHY = os.path.join(HOST, 'results/graph_branch/synth_phys')
OUT = os.path.join(HOST, 'results/graph_branch/summary')
COLS = [('uniform_rel_median', 'field err. (median %)', 100), ('uniform_rel_p95', 'field err. p95 %', 100),
        ('ridge_rel_median', 'near-ridge err. %', 100), ('rot_ridge_err_deg_median', 'ridge loc. err. (deg)', 1),
        ('rot_ridge_err_deg_max', 'ridge loc. max (deg)', 1), ('rot_peak_height_rel_err_median', 'ridge height err. %', 100),
        ('rot_scan_rel_err_median', 'rot. slice err. %', 100), ('trans_scan_rel_err_median', 'disc slice err. %', 100),
        ('plan_success', 'plan succ. %', 100), ('plan_cost_ratio_median', 'plan cost', 1), ('plan_cost_ratio_p90', 'cost p90', 1)]
LABEL = {'morig': 'metric baseline net (original, chart input)', 'morig05': 'metric baseline net (original, chart input, scale 0.05)',
         'ggram': 'graph_gram', 'gmetric': 'graph_metric', 'gmet05': 'graph_metric (scale 0.05)',
         'br1': 'branch K=1', 'br1s': 'branch K=1', 'br4': 'branch K=4', 'br4s': 'branch K=4',
         'br4P': 'branch K=4, l_p', 'br4Ps': 'branch K=4, l_p', 'br4L': 'branch K=4, logsumexp',
         'br4H': 'branch K=4, Huber', 'br4Hs': 'branch K=4, Huber', 'br4PH': 'branch K=4, l_p + Huber',
         'bc4': 'branch K=4, conformal'}
ORDER = ['morig', 'morig05', 'ggram', 'gmetric', 'gmet05', 'br1', 'br1s', 'br4', 'br4s', 'br4P', 'br4Ps', 'br4L', 'br4H', 'br4Hs', 'br4PH',
         'bc4']


def cell(vals, scale):
    vals = [v * scale for v in vals if v is not None]
    if not vals:
        return '-'
    f = '{:.2f}' if scale == 100 else '{:.3g}'
    if len(vals) == 1:
        return f.format(vals[0])
    return (f + ' +- ' + f).format(st.mean(vals), st.stdev(vals))


def table(groups, title):
    lines = ['## ' + title, '']
    out = {}
    for prob in sorted(groups):
        heads = groups[prob]
        cols = [c for c in COLS if any(r.get(c[0]) is not None for rs in heads.values() for r in rs)]
        lines += ['### ' + prob, '', '| head | n | ' + ' | '.join(c[1] for c in cols) + ' |', '|' + '---|' * (len(cols) + 2)]
        for h in sorted(heads, key=lambda k: ORDER.index(k) if k in ORDER else 99):
            rs = heads[h]
            lines.append('| {} | {} | {} |'.format(LABEL.get(h, h), len(rs), ' | '.join(cell([r.get(c[0]) for r in rs], c[2])
                                                                                    for c in cols)))
            out.setdefault(prob, {})[h] = {c[0]: [r.get(c[0]) for r in rs] for c in cols}
        lines.append('')
    return lines, out


def main():
    sup = {}
    for f in glob.glob(os.path.join(SUP, '*', '*_s*.json')):
        prob = os.path.basename(os.path.dirname(f))
        d = json.load(open(f))
        sup.setdefault(prob, {}).setdefault(d['head'], []).append(d)
    phy = {}
    for f in glob.glob(os.path.join(PHY, '*.json')):
        d = json.load(open(f))
        m = re.match(r'^(S\d+)_(.+)_aniso_s(\d+)$', d['run'])
        if not m:
            continue
        prob = 'sector_A{}'.format(m.group(1)[1:])
        phy.setdefault(prob, {}).setdefault(m.group(2), []).append(d)
    lines = ['# Synthetic exact-truth benchmark (models/graph_branch/synth.py)', '',
             'sector_A*: yaw slow sector h = 1 + A exp(-(psi - pi)^2 / 0.5), translation free; disc: hard disc r = 0.15;',
             'both: disc + sector A = 4. Rotational ridge = where the two yaw routes tie (not at the half turn); the',
             "max pure-rotation time exceeds graph_gram's cap of 0.5 (A = 4: 0.90, A = 20: 2.49). Generated by",
             'aggregate_synth.py.', '']
    l1, o1 = table(sup, 'Supervised fit to exact labels (representation)')
    l2, o2 = table(phy, 'Physics-trained (Eikonal only, aniso planar, no labels)')
    lines += l1 + l2
    os.makedirs(OUT, exist_ok=True)
    with open(os.path.join(OUT, 'synth_summary.md'), 'w') as fh:
        fh.write('\n'.join(lines) + '\n')
    with open(os.path.join(OUT, 'synth_summary.json'), 'w') as fh:
        json.dump({'supervised': o1, 'physics': o2}, fh, indent=1)
    print('\n'.join(lines))


if __name__ == '__main__':
    main()
